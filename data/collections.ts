export function getCollectionBySlug(slug: string): Collection | undefined {
  if (!slug) return undefined;
  const s = slug.toLowerCase().trim().replace(/[\s_-]+/g, '');
  if (s === 'ivory' || s === 'ivora') {
    return COLLECTIONS.find(c => c.id === 'ivora');
  }
  if (s === 'speckledbrown' || s === 'terraspeckle') {
    return COLLECTIONS.find(c => c.id === 'speckled-brown');
  }
  if (s === 'greyborne' || s === 'urbanegrey' || s === 'thegreybornecollection') {
    return COLLECTIONS.find(c => c.id === 'greyborne');
  }
  if (s === 'modernsagegreen' || s === 'sagegreen' || s === 'themodernsagegreencollection') {
    return COLLECTIONS.find(c => c.id === 'modern-sage-green');
  }
  if (s === 'terrane' || s === 'theterranecollection') {
    return COLLECTIONS.find(c => c.id === 'terrane');
  }
  if (s === 'modernpink' || s === 'themodernpinkcollection' || s === 'pink') {
    return COLLECTIONS.find(c => c.id === 'modern-pink');
  }
  if (s === 'modernbrown' || s === 'themodernbrowncollection' || s === 'brown') {
    return COLLECTIONS.find(c => c.id === 'modern-brown');
  }
  if (s === 'modernblack' || s === 'themodernblackcollection' || s === 'black') {
    return COLLECTIONS.find(c => c.id === 'modern-black');
  }
  if (s === 'auren' || s === 'theaurencollection') {
    return COLLECTIONS.find(c => c.id === 'auren');
  }
  return COLLECTIONS.find(
    c =>
      c.id.toLowerCase().replace(/[\s_-]+/g, '') === s ||
      c.name.toLowerCase().replace(/[\s_-]+/g, '') === s
  );
}

